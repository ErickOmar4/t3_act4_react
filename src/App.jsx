// App.jsx: componente raíz de la aplicación
function App() {
  // Cualquier variable de JavaScript se puede mostrar con { }
  const nombre = 'Erick'
  const edad = 21
  const estilo = { color: 'tomato', fontSize: '24px' } // estilos en línea = objeto
  const ciudad = 'oaxaca'

  return (
    // REGLA 1: un componente devuelve UN solo elemento padre.
    // El <> </> (fragmento) sirve cuando no quieres un div extra.
    <>
      {/* REGLA 2: así se escriben los comentarios dentro de JSX */}

      {/* REGLA 3: { } ejecuta cualquier expresión de JavaScript */}
      <h1>Hola, {nombre}</h1>
      <p>El año que viene tendrás {edad + 1} años</p>
      <p>{nombre.toUpperCase()}</p>

      {/* REGLA 4: "class" se escribe "className" */}
      <p className="texto">Este párrafo tiene una clase CSS</p>

      {/* REGLA 5: style recibe un objeto, con propiedades en camelCase */}
      <p style={estilo}>Texto con estilo en línea</p>

      <p style={estilo} >{nombre.toUpperCase()} vive en {ciudad.toUpperCase()}</p>

      {/* REGLA 6: todas las etiquetas se cierran, incluso las vacías */}
      <img src="https://placehold.co/100" alt="Ejemplo" />
      <br />
    </>
  )
}

export default App